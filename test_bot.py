def check_answer(answer, keywords):
    answer_lower = answer.lower()
    matched = [kw for kw in keywords if kw.lower() in answer_lower]
    return matched, len(matched) > 0


def run_tests():
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    output_file = f"results_{timestamp}.csv"

    total = len(QUESTIONS)
    passed = 0
    failed = 0
    errors = 0

    print("=" * 60)
    print(f"Запуск автопроверки: {total} вопросов")
    print(f"Результаты: {output_file}")
    print("=" * 60)

    rows = []

    for i, (question, keywords) in enumerate(zip(QUESTIONS, EXPECTED_KEYWORDS), start=1):
        try:
            response = requests.post(
                BOT_URL,
                json={"message": question},
                timeout=60
            )
            data = response.json()
            answer = data.get("reply", "").strip()

            matched_keywords, ok = check_answer(answer, keywords)
            status = "✅ OK" if ok else "❌ FAIL"

            if ok:
                passed += 1
            else:
                failed += 1
                print(f"[{i:02d}/{total}] {status}")
                print(f"       Вопрос: {question[:70]}...")
                print(f"       Ищем:   {keywords}")
                print(f"       Ответ:  {answer[:120]}...")
                print()

            rows.append({
                "№": i,
                "Статус": "OK" if ok else "FAIL",
                "Вопрос": question,
                "Ожидаемые ключевые слова": ", ".join(keywords),
                "Найдено": ", ".join(matched_keywords),
                "Ответ бота": answer
            })

        except requests.exceptions.ConnectionError:
            print(f"[{i:02d}/{total}] ⚠️  Сервер недоступен. Запусти app.py сначала.")
            errors += 1
            rows.append({
                "№": i,
                "Статус": "ERROR",
                "Вопрос": question,
                "Ожидаемые ключевые слова": ", ".join(keywords),
                "Найдено": "",
                "Ответ бота": "Сервер недоступен"
            })
            break

        except Exception as e:
            print(f"[{i:02d}/{total}] ⚠️  ОШИБКА: {e}")
            errors += 1
            rows.append({
                "№": i,
                "Статус": "ERROR",
                "Вопрос": question,
                "Ожидаемые ключевые слова": ", ".join(keywords),
                "Найдено": "",
                "Ответ бота": str(e)
            })

        time.sleep(1)

    with open(output_file, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=["№", "Статус", "Вопрос", "Ожидаемые ключевые слова", "Найдено", "Ответ бота"]
        )
        writer.writeheader()
        writer.writerows(rows)

    print()
    print("=" * 60)
    print(f"ИТОГ:")
    print(f"  Всего вопросов:  {total}")
    print(f"  ✅ Прошли:       {passed}")
    print(f"  ❌ Не прошли:    {failed}")
    if errors:
        print(f"  ⚠️  Ошибки:       {errors}")
    score = round(passed / max(1, total - errors) * 100, 1)
    print(f"  Результат:       {score}%")
    print(f"  Файл:            {output_file}")
    print("=" * 60)


if __name__ == "__main__":
    run_tests()