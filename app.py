df = pd.read_excel("catalog.xlsx")

required_columns = ["Название", "Цена", "Артикул", "Категория"]
for col in required_columns:
    if col not in df.columns:
        raise Exception(f"В файле catalog.xlsx нет колонки: {col}")

extra_cols = []
if "Фото" in df.columns:
    extra_cols.append("Фото")

df = df[required_columns + extra_cols].copy()

df["Название"] = df["Название"].astype(str).str.strip()
df["Цена"] = df["Цена"].astype(str).str.strip()
df["Артикул"] = df["Артикул"].astype(str).str.strip()
df["Категория"] = df["Категория"].astype(str).fillna("").str.strip()

df = df[
    (df["Название"].str.len() > 2) &
    (~df["Название"].str.contains("Бренд|Размер|Свободно|На складе|В пути|Европа|Поиск|Найдено", case=False, na=False))
].copy()

# Чистим цену
df["Цена_число"] = (
    df["Цена"]
    .astype(str)
    .str.replace("от ", "", regex=False)
    .str.replace("₽", "", regex=False)
    .str.replace("руб.", "", regex=False)
    .str.replace("руб", "", regex=False)
    .str.replace(",", ".", regex=False)
    .str.replace(" ", "", regex=False)
    .str.replace("\xa0", "", regex=False)
    .str.replace("По запросу", "", regex=False)
    .str.replace("Позапросу", "", regex=False)
)

df["Цена_число"] = pd.to_numeric(df["Цена_число"], errors="coerce")
df = df.drop_duplicates(subset=["Название", "Артикул"]).reset_index(drop=True)

df_priced = df[df["Цена_число"].notna()].copy()
df_priced = df_priced[df_priced["Цена_число"] > 0].copy()

PRICE_DATA_AVAILABLE = len(df_priced) > 0

print("=" * 50)
print(f"Всего товаров в каталоге: {len(df)}")
print(f"Товаров с ценами: {len(df_priced)}")
print(f"Цены доступны: {PRICE_DATA_AVAILABLE}")
print("=" * 50)


