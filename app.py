df_priced = df_priced[df_priced["Цена_число"] > 0].copy()

PRICE_DATA_AVAILABLE = len(df_priced) > 0

print("=" * 50)
print(f"Всего товаров в каталоге: {len(df)}")
print(f"Товаров с ценами: {len(df_priced)}")
print(f"Цены доступны: {PRICE_DATA_AVAILABLE}")
