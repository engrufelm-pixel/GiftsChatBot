@app.route("/chat", methods=["POST"])
def chat():
    try:
        user_message = request.json.get("message", "").strip()

        if not user_message:
            return jsonify({"reply": "Напишите запрос, и я помогу."})

        query_type = detect_query_type(user_message)

        if query_type == "question":
            reply = answer_question_local(user_message)
            return jsonify({"reply": reply})

        budget = extract_budget(user_message)
        is_vip = detect_vip(user_message)
        gender = detect_gender(user_message)

        if not budget:
            return jsonify({"reply": "Укажите, пожалуйста, бюджет, и я подберу варианты."})

        if not PRICE_DATA_AVAILABLE:
            return jsonify({
                "reply": "Каталог товаров загружен, но в текущей XML-выгрузке отсутствуют цены. Для корректных подборок по бюджету нужен файл с ценами (обычно это отдельная выгрузка price.xml / offers.xml / stock.xml)."
            })

        products = build_selection(
            budget=budget,
            is_vip=is_vip,
            gender=gender,
            query_text=user_message
        )

        if products is None:
            return jsonify({
                "reply": "Каталог загружен, но в текущей выгрузке нет цен. Для подборок по бюджету нужен отдельный файл с ценами."
            })

        if products.empty:
            return jsonify({
                "reply": "К сожалению, в указанном бюджете подходящих товаров не найдено. Попробуйте увеличить бюджет или уточнить запрос."
            })

        reply = format_products_reply(products, is_vip)
        return jsonify({"reply": reply})

    except Exception as e:
        print("Ошибка:", e)
        return jsonify({"reply": "Произошла ошибка. Попробуйте еще раз."})


